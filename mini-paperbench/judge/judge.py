"""간이 judge (경로 B): 리프 1개를 LLM 1회 호출로 0/1 채점한다.

프롬프트 문구는 openai/frontier-evals의 paperbench/judge/constants.py(SimpleJudge)에서 가져왔다.
원본과 다른 점:
- 파일 순위 매기기 호출 없이 제출물의 관련 파일 전체를 넣는다(제출물이 작음).
- 점수 파싱용 두 번째 호출 대신 JSON 스키마(structured output)로 한 번에 받고, 파싱 실패 시 재요청한다.
- 메시지 순서는 논문 → 추가 설명 → 제출물 → 리프 기준. 앞부분이 리프마다 같아서 캐시 할인을 받는다.
"""
import json
import os
import random
import time
from pathlib import Path

from dotenv import load_dotenv
from openai import APIConnectionError, APITimeoutError, InternalServerError, OpenAI, RateLimitError
from pydantic import BaseModel, Field, ValidationError
from tenacity import retry, retry_if_exception_type, stop_after_attempt, wait_exponential

load_dotenv()

MAX_PARSE_RETRIES = 3  # JSON 파싱 실패 시 재요청 최대 횟수
# 출력 길이 상한. 작은 모델은 가끔 같은 문장을 끝없이 반복한다(호출 1번이 6분 넘게 걸린 적이 있다).
# 잘리면 JSON이 깨져서 재요청된다. Gemini 출력은 100~800 토큰이라 영향이 없다.
MAX_OUTPUT_TOKENS = 2048

SYSTEM_PROMPT = """You are judging a candidate's attempt to reproduce a research paper.

You will first be given the research paper, which you should read carefully and refer to as the ground truth for what constitutes a correct implementation and reproduction.

Following that, you will be presented with the candidate's submission: a set of files that attempts
to reproduce the paper. The candidate has been asked to include a `reproduce.sh` script that, when executed, should run the full reproduction process and generate all results in the paper. If the script exists, we have already run it and included any output logs in the file `reproduce.log`. Any other files generated by the script may also be present, such as results, plots, or artifacts. If either `reproduce.sh` or `reproduce.log` is missing, you should consider any criteria relying on it to have failed.

To judge the submission, we have prepared a full rubric describing fine-grained criteria for different aspects of the paper.

Your task is to check the submission and its outputs for ONE specific criterion from this rubric."""

CRITERION_PROMPT = """The full grading rubric for the paper hierarchically decomposes various aspects of the paper. To provide more context for the criterion you are currently grading, here are some of the preceding criteria (DO NOT grade this, this is just for context):
<preceding_criteria>
{preceding_criteria}
</preceding_criteria>

Now, here is the criterion that you are grading:
<criterion>
{criterion}
</criterion>

The criterion you are grading is of type {task_category} - {task_category_question}"""

TASK_CATEGORY_QUESTIONS = {
    "Code Development": (
        "Does the code in the submission contain a correct implementation of this?"
        " Note: mere instructions or descriptions of implementations are not sufficient;"
        " you should check whether there is actual code that implements the requirement."
    ),
    "Code Execution": "Does running the reproduce.sh script lead to this being successfully executed?",
    "Result Analysis": "Did the reproduce.sh script execution produce evidence that agrees with these results?",
}

# 원본 GRADING_PROMPT에서 마지막 출력 형식만 JSON으로 바꿨다.
GRADING_PROMPT = """You will now evaluate the submission above for the given criterion.

Think through it in 3 parts:
1. Expectations: Read the paper carefully to identify the parts relevant to your criterion. Describe what you expect correct resolution to look like, and what you will specifically look for in the submission.
2. Reality: Explore the files provided for the submission along with the output logs to identify the parts that are relevant to the resolution criteria. Comment on how they compare to your expectations, and whether the attempt meets the resolution criteria. Be explicit about which files you are referring to.
3. Score: Reason about whether the criteria has been met. Give a score of either 0 or 1 depending on whether the criteria has been met.

Other notes:
- You must always provide a score. If you have any uncertainties, make them clear in your discussion.
- All the files and logs from the submission attempt have been provided to you. If anything appears to be missing, assume that the attempt failed to produce it (treat it as a failure).
- Be strict and thorough in grading your resolution criteria, but do not check for things that are outside of your scope.

Respond with a single JSON object and nothing else:
{"reason": "<your expectations, reality and reasoning, concisely>", "score": <0 or 1>}"""

# 원본 _get_whitelisted_files의 확장자 목록
DOC_EXT = {".md", ".txt", ".rst"}
CODE_EXT = {".py", ".R", ".Rmd", ".m", ".jl", ".c", ".h", ".cpp", ".hpp", ".cc", ".cxx", ".hxx",
            ".java", ".js", ".ts", ".scala", ".go", ".rs", ".sh",
            ".config", ".cfg", ".json", ".yaml", ".yml", ".toml", ".ini"}
TABLE_EXT = {".csv", ".tsv", ".psv", ".json", ".jsonl", ".html", ".xml", ".yaml", ".yml",
             ".toml", ".arff", ".tex", ".svm", ".libsvm"}
SKIP_DIRS = {"venv", ".venv", ".env", "wandb", ".egg-info", ".git", ".github", "__pycache__", "node_modules"}


class JudgeOutput(BaseModel):
    reason: str
    score: int = Field(ge=0, le=1)


def read_submission(submission_dir: Path, task_category: str) -> str:
    """제출물에서 이 리프 종류에 관련된 파일을 원본 judge의 <FILE:...> 형식으로 이어 붙인다."""
    exts = DOC_EXT | TABLE_EXT if task_category == "Result Analysis" else DOC_EXT | CODE_EXT
    parts = []
    for path in sorted(Path(submission_dir).rglob("*")):
        rel = path.relative_to(submission_dir)
        if not path.is_file() or path.suffix not in exts or path.name.startswith("._"):
            continue
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        content = path.read_text(errors="replace")
        parts.append(f"<FILE:{rel}>\n{content if content.strip() else '(FILE IS EMPTY)'}\n</FILE:{rel}>")
    return "\n\n".join(parts)


def build_messages(paper_md: str, addendum: str, submission_dir: Path, leaf: dict) -> list[dict]:
    category = leaf["task_category"]
    sub = Path(submission_dir)
    reproduce_sh = (sub / "reproduce.sh").read_text() if (sub / "reproduce.sh").exists() else "(Does not exist)"
    reproduce_log = (sub / "reproduce.log").read_text() if (sub / "reproduce.log").exists() else "(Does not exist)"

    files_label = (
        "Here are the most relevant docs and the files touched (i.e. modified or created) during the reproduce.sh execution, concatenated:"
        if category == "Result Analysis"
        else "Here are the most relevant files included in the submission attempt, concatenated:"
    )
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"The paper is below:\n{paper_md}"},
        {"role": "user", "content": f"If included with the paper, you will now be shown an addendum which provides clarification for the paper and how to evaluate its reproduction:\n<addendum>\n{addendum or '(NO ADDENDUM GIVEN)'}\n</addendum>"},
        {"role": "user", "content": f"{files_label}\n<files>\n{read_submission(sub, category)}\n</files>"},
        {"role": "user", "content": f"Here is the `reproduce.sh` provided in the submission, if any:\n<reproduce.sh>\n{reproduce_sh}\n</reproduce.sh>"},
    ]
    if category != "Code Development":
        messages.append({"role": "user", "content": f"Here is the `reproduce.log` provided in the submission, if any:\n<reproduce.log>\n{reproduce_log}\n</reproduce.log>"})
    messages += [
        {"role": "user", "content": CRITERION_PROMPT.format(
            preceding_criteria="".join(f" -> {r}\n" for r in leaf["preceding"]),
            criterion=leaf["requirements"],
            task_category=category,
            task_category_question=TASK_CATEGORY_QUESTIONS.get(category, "Does the submission satisfy this criterion?"),
        )},
        {"role": "user", "content": GRADING_PROMPT},
    ]
    return messages


def _client() -> OpenAI:
    return OpenAI(base_url=os.environ["LLM_BASE_URL"], api_key=os.environ["LLM_API_KEY"])


@retry(
    retry=retry_if_exception_type((RateLimitError, APIConnectionError, APITimeoutError, InternalServerError)),
    wait=wait_exponential(multiplier=2, max=60),
    stop=stop_after_attempt(5),
    reraise=True,
)
def _call(client: OpenAI, messages: list[dict]):
    return client.chat.completions.create(
        model=os.environ["LLM_MODEL"],
        messages=messages,
        max_tokens=MAX_OUTPUT_TOKENS,
        # json_object 모드에서는 reason 안의 따옴표가 이스케이프되지 않아 파싱이 자주 깨졌다.
        # 스키마를 주면 디코딩 단계에서 유효한 JSON이 강제된다.
        response_format={
            "type": "json_schema",
            "json_schema": {"name": "judge_output", "schema": JudgeOutput.model_json_schema()},
        },
    )


def judge_leaf(paper_md: str, addendum: str, submission_dir: Path, leaf: dict) -> dict:
    """리프 1개 채점. {"score", "reason"}에 측정용 "usage", "parse_retries"를 덧붙여 돌려준다.

    MOCK_JUDGE=1이면 LLM을 부르지 않고 MOCK_DELAY_SEC 기다린 뒤 무작위 0/1을 돌려준다.
    """
    if os.environ.get("MOCK_JUDGE") == "1":
        time.sleep(float(os.environ.get("MOCK_DELAY_SEC", "3")))
        usage = {"input_tokens": 0, "output_tokens": 0, "cached_tokens": 0, "calls": 0}
        return {"score": random.randint(0, 1), "reason": "mock", "usage": usage, "parse_retries": 0}
    client = _client()
    messages = build_messages(paper_md, addendum, submission_dir, leaf)
    usage = {"input_tokens": 0, "output_tokens": 0, "cached_tokens": 0, "calls": 0}
    last_error = None
    for attempt in range(1 + MAX_PARSE_RETRIES):
        resp = _call(client, messages)
        u = resp.usage
        usage["calls"] += 1
        usage["input_tokens"] += u.prompt_tokens
        usage["output_tokens"] += u.completion_tokens
        details = getattr(u, "prompt_tokens_details", None)
        usage["cached_tokens"] += (getattr(details, "cached_tokens", 0) or 0) if details else 0
        text = resp.choices[0].message.content or ""
        try:
            out = JudgeOutput.model_validate(json.loads(text))
            return {"score": out.score, "reason": out.reason, "usage": usage, "parse_retries": attempt}
        except (json.JSONDecodeError, ValidationError) as e:
            last_error = f"{type(e).__name__}: {text[:200]!r}"
    raise ValueError(f"judge output not parseable after {1 + MAX_PARSE_RETRIES} calls: {last_error}")
